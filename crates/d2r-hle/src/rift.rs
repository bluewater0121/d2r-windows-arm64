//! 宿主调用 `0x89`：秘境出口改道（参考工程 `dm_rift.c` 的 `svc_rift_exit`）。
//!
//! 这是一个**分支门**，挂在 `main+0x7cc1e0`（「按出口砖的连接换关」入口）。门块
//! （`main.patched.bin` 里 `0x33d90a0`）的形状是：
//!
//! ```text
//! 0x33d90a0: stp x8, xzr, [sp, #-0x10]!   ; 先把客人的 x8 存起来
//! ...
//! 0x33d90c0: blr x30                       ; 调宿主（就是本模块这个函数）
//! 0x33d90c8: cbz w8, #0x33d90d4            ; 宿主写的 w8 == 0 → 执行原指令
//! 0x33d90cc: ldp x8, xzr, [sp], #0x10
//! 0x33d90d0: b  #0x634000                  ; w8 != 0 → 改道「按关卡号换关」
//! 0x33d90d4: ldp x8, xzr, [sp], #0x10
//! 0x33d90dc: b  #0x7cc1e4                  ; 原版路径
//! ```
//!
//! 也就是说 `w8` 是**宿主必须写回的返回值**。这个号以前没登记，落进内核
//! `svc.rs` 的 `unknown()`：那里只写 `x0 = 0`，`x8` 保持客人自己的旧值，于是
//! `cbz w8` 拿到的是垃圾——旧值非 0 时，换关会带着「出口砖的两个参数」跳进
//! 「按关卡号换关」，那边按关卡号查记录的守卫查不到（`main+0x634018` /
//! `0x634080` / `0x634088` / `0x634094` 四条 `cbz/cbnz → 0x6341a4`），走 main
//! 自己的致命块：
//!
//! ```text
//! 0x6341b8: mov w0, #6 ; mov x1, ""(0x1d5a900) ; mov x2, x30 ; mov w3, wzr
//! 0x6341c4: bl  <report(6, "", lr, 0)>          ; main+0xde1850
//! 0x6341c8: mov w0, #-1
//! 0x6341cc: bl  exit                            ; 导入 `exit`（GOT 0x211e608）
//! ```
//!
//! 于是 `exit(-1)` → newlib `_exit` → `nn::os::ExitProcess`（sdk+0x34cab0）→
//! `svcExitProcess`（我们当时同样没实现，占位返回）→ SDK 的「不可达」兜底
//! `AbortImpl("","","",0)` → `svcBreak(0,&Result,4)`，也就是日志里那条
//! `Break reason=0x0`。整条链在 73s 那次的 Error 级帧链里完整出现过。
//!
//! 参考宿主 `svc_rift_exit()` 只在**秘境局**里改道（`rift_exit_active()`：局内状态
//! `ST_RUN/ST_DONE` + 同一玩家 + 人在秘境图），否则一律 `x8 = 0`，交给原版指令。
//! 本移植还没有秘境玩法，所以这里恒按「非秘境局」处理：写 `x8 = 0`，其余寄存器
//! 原样放行——与参考工程在非秘境局时的行为逐位一致。

use d2r_abi::Regs;

/// `0x89`：按出口砖的连接换关入口，永远放行原版路径。
pub fn rift_exit(regs: &mut Regs) -> bool {
    // 参考实现：非秘境局 `regs[8] = 0`，门块据此执行原指令回 `0x7cc1e4`。
    regs.set_x(8, 0);
    true
}
